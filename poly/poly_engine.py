import uuid as _uuid
import hashlib as _hashlib
import time as _time
import json as _json
import platform as _platform
from datetime import datetime as _datetime, timezone as _timezone


def generate_build_identity() -> dict:
    """
    Generate a unique build identity for CI provenance.

    Returns:
      build_id
      build_sha256
      timestamp
      platform
      build_ts
      sym_prefix
    """
    build_id = str(_uuid.uuid4())
    timestamp = _datetime.now(_timezone.utc).isoformat()
    platform_str = (
        f"{_platform.system()}-"
        f"{_platform.machine()}-"
        f"py{_platform.python_version()}"
    )

    entropy = (
        f"{build_id}|{timestamp}|"
        f"{platform_str}|{_time.monotonic_ns()}"
    )
    build_sha = _hashlib.sha256(entropy.encode()).hexdigest()

    return {
        "build_id": build_id,
        "build_sha256": build_sha,
        "timestamp": timestamp,
        "platform": platform_str,
        "build_ts": int(_time.time()),
        "sym_prefix": build_id.replace("-", "")[:6],
    }


def generate_build_manifest(
    source_file: str,
    output_binary: str,
    identity: dict = None,
    source_revision: str = "UNKNOWN",
) -> dict:
    """
    Generate a CI build manifest embedding provenance + build identity.

    Writes <output_binary>.manifest.json alongside the binary.
    """
    if identity is None:
        identity = generate_build_identity()

    import os

    binary_sha = ""
    binary_size = 0

    if os.path.exists(output_binary):
        h = _hashlib.sha256()

        with open(output_binary, "rb") as f:
            for chunk in iter(lambda: f.read(65536), b""):
                h.update(chunk)

        binary_sha = h.hexdigest()
        binary_size = os.path.getsize(output_binary)

    manifest = {
        "version": "2.0",
        "source_file": source_file,
        "output_binary": output_binary,
        "binary_sha256": binary_sha,
        "binary_size": binary_size,
        "build_id": identity["build_id"],
        "build_sha256": identity["build_sha256"],
        "timestamp": identity["timestamp"],
        "platform": identity["platform"],
        "source_revision": source_revision,
        "provenance": {
            "build_id": identity["build_id"],
            "build_sha256": identity["build_sha256"],
            "timestamp": identity["timestamp"],
            "platform": identity["platform"],
            "source_revision": source_revision,
        },
        "manifest_sha256": "",
    }

    manifest_path = output_binary + ".manifest.json"

    canonical = _json.dumps(
        manifest,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")

    manifest["manifest_sha256"] = _hashlib.sha256(canonical).hexdigest()

    with open(manifest_path, "w") as f:
        _json.dump(manifest, f, indent=2)

    return manifest
