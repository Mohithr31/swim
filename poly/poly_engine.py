"""
poly_engine.py
--------------
JOCKY Polymorphic Build Engine

PURPOSE:
  Every time this runs it produces a binary with:
    - Different SHA256 hash
    - Different build ID embedded in the binary
    - Different symbol names (obfuscated)
    - Different compile-time constants
    - Unique per-build AES key baked in

  This defeats:
    - AV file reputation databases (hash always different)
    - Signature matching (structure always different)
    - Static analysis (symbols scrambled)

USAGE:
  python3 poly_engine.py --src ../runtime --out ./build
  python3 poly_engine.py --src ../runtime --out ./build --vt-key YOUR_KEY
"""

