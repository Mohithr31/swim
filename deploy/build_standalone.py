"""Build a single-file JOCKY forensic agent for the current host OS.

PyInstaller is platform-native: build the Linux ELF on Linux and the Windows
PE executable on Windows. The resulting artifact contains the Python runtime
and the JOCKY agent/collector dependencies, so the target machine does not
need Python installed.

Each build receives a unique build identity (UUID + UTC timestamp). The
identity is embedded in the application metadata, which makes independently
built artifacts byte-different and gives investigators a traceable build ID.
This is build provenance, not antivirus/EDR evasion.
"""
from pathlib import Path
import argparse
import hashlib
import json
import os
import platform
import shutil
import subprocess
import sys
import uuid
import importlib.util

VERSION = "5.0"
from datetime import datetime, timezone


ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "dist"
IDENTITY_MODULE = ROOT / "agent" / "build_identity.py"


def git_revision() -> str | None:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True, stderr=subprocess.DEVNULL
        ).strip()
    except Exception:
        return None

def make_identity() -> dict:
    now = datetime.now(timezone.utc)
    return {
        "build_id": str(uuid.uuid4()),
        "built_at": now.isoformat(),
        "version": VERSION,
        "platform": platform.system().lower(),
        "machine": platform.machine(),
        "python": platform.python_version(),
        "source_revision": git_revision(),
        "builder": "deploy/build_standalone.py",
        "security_boundary": "forensic collection and detection; no security-control bypass",
    }


def write_identity(identity: dict) -> None:
    # BUILD_IDENTITY is imported by the agent and indexed like a dictionary.
    # Do not serialize the dictionary to a JSON string here.
    # Using repr(identity) embeds a real Python dict in the generated module.
    source = (
        "# AUTO-GENERATED by deploy/build_standalone.py\n"
        "# Build provenance only; do not edit manually.\n"
        f"BUILD_IDENTITY = {identity!r}\n"
        "BUILD_ID = BUILD_IDENTITY['build_id']\n"
    )
    IDENTITY_MODULE.write_text(source, encoding="utf-8")


# Common Linux daemon names to use as binary names (blends into pstree)
MASQUERADE_PROFILES = {
    "netd":       "netd",
    "dbus":       "dbus-daemon",
    "journal":    "systemd-journald",
    "udevd":      "systemd-udevd",
    "logrotate":  "logrotate",
    "cron":       "cron",
    "rsyslog":    "rsyslogd",
    "polkit":     "polkitd",
    "acpid":      "acpid",
    "snapd":      "snapd",
    "networkd":   "systemd-networkd",
    "resolved":   "systemd-resolved",
    "sshd":       "sshd",
    "chronyd":    "chronyd",
    "nmbd":       "nmbd",
}


def artifact_name(system: str, masquerade: str | None = None) -> str:
    if system == "Windows":
        return "jocky-agent-windows.exe"
    # On Linux the binary filename IS the process name shown in pstree.
    # If a masquerade name was requested, use it directly as the binary name.
    if masquerade:
        # Resolve profile alias → real name
        resolved = MASQUERADE_PROFILES.get(masquerade, masquerade)
        return resolved
    return "jocky-agent-linux"


def ensure_pyinstaller() -> bool:
    """Ensure the dashboard/build environment has PyInstaller available.

    The dashboard is intended to be the build surface, so a missing PyInstaller
    installation should not immediately turn into a cryptic module-not-found
    failure. Automatic bootstrap can be disabled with
    JOCKY_AUTO_INSTALL_BUILD_TOOLS=0.
    """
    if importlib.util.find_spec("PyInstaller") is not None:
        return True

    if os.environ.get("JOCKY_AUTO_INSTALL_BUILD_TOOLS", "1").lower() in {"0", "false", "no"}:
        print("PyInstaller is not installed and automatic build-tool installation is disabled.", file=sys.stderr)
        return False

    print("PyInstaller is not installed. Installing it for the dashboard build…")
    result = subprocess.run(
        [sys.executable, "-m", "pip", "install", "pyinstaller>=6.0"],
        cwd=ROOT,
        text=True,
    )
    if result.returncode != 0:
        print(
            "Unable to install PyInstaller automatically. Install PyInstaller in the "
            "same Python environment used by the JOCKY server, then retry the dashboard build.",
            file=sys.stderr,
        )
        return False
    return importlib.util.find_spec("PyInstaller") is not None


def main() -> int:
    parser = argparse.ArgumentParser(description="Build a JOCKY forensic agent binary")
    parser.add_argument(
        "--masquerade",
        default=None,
        metavar="NAME_OR_PROFILE",
        help=(
            "Linux only. Name the compiled binary after a legitimate daemon so it "
            "blends into pstree/ps output on the target. Accepts either a profile "
            "key (e.g. 'journal', 'cron', 'sshd') or a custom name (e.g. 'systemd-journald'). "
            "Authorized forensic / red-team deployments only."
        ),
    )
    parser.add_argument(
        "--list-profiles",
        action="store_true",
        help="Print all available masquerade profile keys and exit.",
    )
    cli = parser.parse_args()

    if cli.list_profiles:
        print("Available masquerade profiles (--masquerade <key>):")
        for key, val in MASQUERADE_PROFILES.items():
            print(f"  {key:<14} → {val}")
        return 0

    system = platform.system()
    if system not in {"Windows", "Linux"}:
        print("Standalone builds are supported on Windows and Linux only.")
        return 2

    if not ensure_pyinstaller():
        return 4

    identity = make_identity()
    write_identity(identity)
    DIST.mkdir(parents=True, exist_ok=True)

    masquerade = cli.masquerade if system == "Linux" else None
    # Resolve profile alias → real name for PyInstaller --name flag
    if masquerade:
        resolved_name = MASQUERADE_PROFILES.get(masquerade, masquerade)
    else:
        resolved_name = "jocky-agent-windows" if system == "Windows" else "jocky-agent-linux"

    name = resolved_name
    command = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--clean",
        "--noconfirm",
        "--onefile",
        "--name",
        name,
        "--paths",
        str(ROOT),
        str(ROOT / "agent" / "jocky_agent.py"),
    ]

    if masquerade:
        print(f"Masquerade: binary will be named '{resolved_name}' → blends as that process in pstree")
    print(f"Building JOCKY single-file agent for {system}")
    print(f"Build ID: {identity['build_id']}")
    print("Target: no Python installation required on the deployment machine")

    result = subprocess.run(command, cwd=ROOT)
    if result.returncode != 0:
        return result.returncode

    produced = DIST / (name + (".exe" if system == "Windows" else ""))
    target = DIST / artifact_name(system, masquerade)
    if produced.resolve() != target.resolve() and produced.exists():
        shutil.copy2(produced, target)

    if not target.exists():
        print(f"Build completed but artifact was not found: {target}")
        return 3

    sha256 = hashlib.sha256(target.read_bytes()).hexdigest()
    manifest = {
        **identity,
        "artifact": target.name,
        "sha256": sha256,
        "size_bytes": target.stat().st_size,
        "artifact_type": "PE" if system == "Windows" else "ELF",
    }
    manifest_path = DIST / f"{target.name}.manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    manifest_sha256 = hashlib.sha256(manifest_path.read_bytes()).hexdigest()
    manifest["manifest_sha256"] = manifest_sha256
    manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    print(f"Artifact: {target}")
    print(f"SHA256:   {sha256}")
    print(f"Manifest: {manifest_path}")
    print("Build complete. Build the other platform on its native OS.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
