"""
JOCKY Language — C Code Generator (Authoritative)

Transpiles a Module AST into a C translation unit that links
against jocky_runtime.{h,c}.

For each 'collect <op>' in the module, emits a call to
jocky_collect_<op>() in main(). Also emits a startup printf
announcing the module name.

Public API:
    generate_c_code(module: Module) -> str
    CodeGeneratorError
"""

from src.ast_nodes import Module, CollectionOperation
from src.parser import ALLOWLISTED_OPERATIONS


class CodeGeneratorError(Exception):
    """Raised when C code cannot be generated."""
    pass


# Map op_type → C runtime function name
_RUNTIME_MAP = {
    "system": "jocky_collect_system",
    "processes": "jocky_collect_processes",
    "network": "jocky_collect_network",
    "users": "jocky_collect_users",
    "logs": "jocky_collect_logs",
    "filesystem": "jocky_collect_filesystem",
    "services": "jocky_collect_services",
    "software": "jocky_collect_software",
    "scheduled_tasks": "jocky_collect_scheduled_tasks",
    "environment": "jocky_collect_environment",
    "mounts": "jocky_collect_mounts",
    "disk_usage": "jocky_collect_disk_usage",
    "network_config": "jocky_collect_network_config",
    # These are implemented by the Python forensic collectors; the native
    # runtime exposes safe no-op/metadata hooks so generated binaries remain
    # linkable while the central agent performs the richer collection.
    "drivers": "jocky_collect_drivers",
    "browser": "jocky_collect_browser",
    "email": "jocky_collect_email",
    "memory": "jocky_collect_memory",
    "registry": "jocky_collect_registry",
    "live_events": "jocky_collect_live_events",
    "security_telemetry": "jocky_collect_security_telemetry",
    "location": "jocky_collect_location",
    "recovery": "jocky_collect_recovery",
    "offline": "jocky_collect_offline",
    "removable_media": "jocky_collect_removable_media",
}


def generate_c_code(module: Module) -> str:
    """
    Generate a C source string from a Module AST.

    Raises:
        CodeGeneratorError: if any operation has no runtime mapping.
    """
    lines = [
        "/* AUTO-GENERATED by JOCKY codegen — do not edit by hand. */",
        '#include <stdio.h>',
        '#include "jocky_runtime.h"',
        "",
        "int main(void) {",
        f'    printf("[JOCKY] Starting forensic collection module: %s\\n", "{module.name}");',
    ]

    for op in module.operations:
        if op.op_type not in _RUNTIME_MAP:
            raise CodeGeneratorError(
                f"No runtime mapping for operation '{op.op_type}' at line {op.line}."
            )
        lines.append(f"    {_RUNTIME_MAP[op.op_type]}();")

    lines += [
        '    printf("[JOCKY] Collection complete.\\n");',
        "    return 0;",
        "}",
        "",
    ]

    return "\n".join(lines)
